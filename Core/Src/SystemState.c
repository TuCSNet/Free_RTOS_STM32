// CODE FOR UART
void DisplayThread(void *argument)
{
	TaskStatus_t *taskArray = NULL;
	char pcBuf[100];
	char* status;
	uint32_t totalTime;
	uint32_t numberTask = uxTaskGetNumberOfTasks();

	while (1)
	{
		if(HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13) == GPIO_PIN_RESET)
		{//Allocate memory for Array that stores information
			taskArray = pvPortMalloc(
					numberTask * sizeof(TaskStatus_t));
			if(taskArray != NULL)
			{
				uxTaskGetSystemState(taskArray, numberTask, &totalTime);
				snprintf(pcBuf, sizeof(pcBuf), "We have total of task: %lu\r\n"
						"Total of time: %lu\r\n",
						uxTaskGetNumberOfTasks(), totalTime);
				HAL_UART_Transmit(&huart2, (uint8_t*) pcBuf, strlen(pcBuf),
						HAL_MAX_DELAY);

				for (int i = 0; i < numberTask; ++i)
				{
					snprintf(pcBuf, sizeof(pcBuf), "\r\nThread name: %s\r\n", taskArray[i].pcTaskName);
					HAL_UART_Transmit(&huart2, (uint8_t*)pcBuf, strlen(pcBuf), HAL_MAX_DELAY);

					switch(taskArray[i].eCurrentState)
					{
					case 0 : status = "RUNNING" ; break;
					case 1 : status = "READY" ; break;
					case 2 : status = "BLOCKED" ; break;
					case 3 : status = "SUSPENDED" ; break;
					case 4 : status = "DELETED" ; break;
					default : status = "UNKNOWN" ; break;
					}

					snprintf(pcBuf, sizeof(pcBuf), "Current State: %s\r\n", status);
					HAL_UART_Transmit(&huart2, (uint8_t*)pcBuf, strlen(pcBuf), HAL_MAX_DELAY);

					snprintf(pcBuf, sizeof(pcBuf), "Time spent: %lu\r\n", taskArray[i].ulRunTimeCounter);
					HAL_UART_Transmit(&huart2, (uint8_t*)pcBuf, strlen(pcBuf), HAL_MAX_DELAY);
				}

			}

			vPortFree(taskArray);
		}
		while(HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13) == GPIO_PIN_RESET)
		{
			osDelay(10);
		}
	}
}


